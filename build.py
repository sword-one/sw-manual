def head(title, css):
    return f"""<!doctype html>
<html lang="ja">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow">
<title>{e(title)}</title>
<link rel="stylesheet" href="{css}">
</head>
<body>
<div class="wrap">
"""


FOOT = f"""  <footer><span>わからないことは山口まで。 / 最終更新 {UPDATED}</span></footer>
</div>
</body>
</html>
"""


def sec(n, title, body):
    return f'  <section>\n    <h2><span class="num">{n}</span>{e(title)}</h2>\n{body}  </section>\n\n'


def build_page(p):
    out = [head(p["title"], "../assets/style.css")]
    out.append('  <nav class="topnav"><a href="../index.html">← 一覧にもどる</a><span class="site">ソードワン 自動化マニュアル</span></nav>\n\n')
    kc, kt = p["kind"]
    out.append(f"""  <header>
    <div class="eyebrow">{e(p['eyebrow'])}</div>
    <h1>{e(p['h1'])}</h1>
    <div class="tags"><span class="tag {kc}">{e(kt)}</span><span class="tag accent">{e(p['where'])}</span></div>
    <p class="lead">{e(p['lead'])}</p>
  </header>

""")
    n = 0

    def nxt():
        nonlocal n
        n += 1
        return n

    out.append(sec(nxt(), "何が変わった?", f"""    <div class="ba">
      <div class="card before"><span class="label">これまで</span><p>{e(p['before'])}</p></div>
      <div class="arrow">→</div>
      <div class="card after"><span class="label">いま</span><p>{e(p['after'])}</p></div>
    </div>
"""))

    rows = "".join(f'        <tr><td class="c">{e(a)}</td><td>{e(b)}</td></tr>\n' for a, b in p["timing"])
    body = f'    <div class="cols"><table><tbody>\n{rows}    </tbody></table></div>\n'
    if p.get("timing_note"):
        body += f'    <p>{e(p["timing_note"])}</p>\n'
    out.append(sec(nxt(), "いつ動く?", body))

    items = "".join(
        f'      <li><div class="who {c}">{e(w)}</div><div class="body"><strong>{e(s)}</strong>'
        + (f'<span>{e(d)}</span>' if d else "") + "</div></li>\n"
        for c, w, s, d in p["flow"])
    out.append(sec(nxt(), "全体の流れ", f'    <ol class="flow">\n{items}    </ol>\n'))

    for t, raw in p.get("extra", []):
        out.append(sec(nxt(), t, raw))

    bubbles = "".join(f'      <div class="bubble">{e(s)}</div>\n' for s in p["say"])
    note = f'      <p style="color:var(--sub)">{e(p["say_note"])}</p>\n' if p.get("say_note") else ""
    hum = "".join(f"        <li>{e(h)}</li>\n" for h in p["human"])
    out.append(sec(nxt(), "Claudeへの頼み方と、人がやること", f"""    <div class="two">
      <div class="card say"><span class="tag claude">こう話しかける</span>
{bubbles}{note}      </div>
      <div class="card"><span class="tag human">人がやること</span>
        <ul>
{hum}        </ul>
      </div>
    </div>
"""))

    rows = "".join(f'        <tr><td class="c">{e(a)}</td><td>{e(b)}</td></tr>\n' for a, b in p["tools"])
    out.append(sec(nxt(), "使っている道具", f'    <div class="cols"><table><tbody>\n{rows}    </tbody></table></div>\n'))

    if p.get("conditions"):
        li = "".join(f"        <li>{e(c)}</li>\n" for c in p["conditions"])
        out.append(sec(nxt(), "動くための条件", f'    <div class="card">\n      <ul>\n{li}      </ul>\n    </div>\n'))

    if p.get("faq"):
        d = "".join(f"      <details><summary>{e(q)}</summary><p>{e(a)}</p></details>\n" for q, a in p["faq"])
        out.append(sec(nxt(), "こんなときは", f'    <div class="faq">\n{d}    </div>\n'))

    nt = "".join(
        f'    <div class="note"><strong>{e(s)}</strong>' + (f"<p>{e(b)}</p>" if b else "") + "</div>\n"
        for s, b in p["notes"])
    out.append(sec(nxt(), "気をつけてほしいこと", nt))

    out.append(FOOT)
    return "".join(out)


