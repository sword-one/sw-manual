def sec(n, title, body):
    return f'  <section>\n    <h2><span class="num">{n}</span>{e(title)}</h2>\n{body}  </section>\n\n'


def build_page(p):
    out = [head(p["title"], "../assets/style.css")]
    out.append('  <nav class="topnav"><a href="../index.html">← 一覧にもどる</a><span class="site">ソードワン 自動化マニュアル</span></nav>\n\n')
    kc, kt = p["kind"]
